"""**Exercise 12 — Function Returning Multiple Values**"""

#Define a function stats(values) that returns two values: the average of the list, and its range (max - min).
#You may use the built-in sum(), len(), max() and min() functions here.
#Test it with returns = [0.01, -0.02, 0.03, 0.015], and unpack the two results into separate variables.
#Tip: A function can return several values separated by a comma: return avg, spread. Unpack with avg, spread = stats(returns).

def stats(values):
  avg = sum(values) / len(values)
  spread = max(values) - min(values)
  return avg, spread

returns = [0.01, -0.02, 0.03, 0.015]

avg, spread = stats(returns)

print("Average: ", avg)
print("Range: ", spread)

