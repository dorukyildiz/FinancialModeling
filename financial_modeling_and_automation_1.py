"""**Exercise 23 — Savings Goal Tracker**"""

#Start with savings = 0, monthly_deposit = 200, and goal = 3000.
#Use a while loop to add monthly_deposit to savings each month and print the month number and current savings, stopping once savings >= goal.
#Print the total number of months it took to reach the goal.

savings = 0
monthly_deposit = 200
goal = 3000

month = 0

while savings < goal:
    savings += monthly_deposit
    month += 1
    print("Month", month, "| Savings:", savings)

print("Goal reached in", month, "months")