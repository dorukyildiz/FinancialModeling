"""**Exercise 14 — Years to Reach a Savings Goal**"""

#Define years_to_goal(principal, rate, goal) that uses a while loop to grow the principal at the given rate until it
#reaches or exceeds the goal.
#The function returns the number of years needed.
#Test it with 1000, 0.06 and 2000.
#Tip: Make sure the balance changes inside the loop, otherwise the condition never becomes False and
#your program runs forever.

def years_to_goal(principal, rate, goal):
    balance = principal
    years = 0
    while balance < goal:
        balance = balance * (1 + rate)
        years += 1
    return years


years_to_goal(1000, 0.06, 2000)