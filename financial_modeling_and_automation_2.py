"""**Exercise 13 — Count Profitable Trades**"""

#Define count_winners(pnl_list) that takes a list of profit and loss values and returns how many of them are strictly positive.
#Test it with [50, -20, 30, -10, 0, 75].
#Tip: Initialise your counter to 0 before the loop, increment it inside the if, and return it after the loop finishes.

def count_winners(pnl_list):
    count = 0
    for pnl in pnl_list:
        if pnl > 0:
            count += 1
    return count

