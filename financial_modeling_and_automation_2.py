"""**Exercise 8 — Average of a List**"""

#Define average(values) that takes a list of numbers and returns their mean.
#Use a for loop and an accumulator inside the function (do not use the built-in sum()).
#Test it with a list of daily closing prices.
#Tip: Remember that len(values) gives the number of items — divide the accumulated total by it at the end, after the loop, not inside it.

def average(values):
    total = 0
    for v in values:
        total += v
    return total / len(values)

closing_prices = [101.5, 102.3, 99.8, 100.4, 103.0]

print("Average closing price:", average(closing_prices))

